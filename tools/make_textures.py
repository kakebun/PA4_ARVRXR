import os
import numpy as np
from PIL import Image, ImageFilter

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "textures")
rng = np.random.default_rng(241280)


def tile_noise(size, cells, octaves=4):
    """Tileable value noise in [0,1]."""
    acc = np.zeros((size, size))
    amp, total = 1.0, 0.0
    for o in range(octaves):
        c = cells * (2 ** o)
        grid = rng.random((c, c))
        img = Image.fromarray((grid * 255).astype(np.uint8))
        # wrap-pad then resize so the result tiles
        big = np.tile(np.array(img), (3, 3))
        big = Image.fromarray(big).resize((size * 3, size * 3), Image.BICUBIC)
        acc += amp * (np.array(big)[size:2 * size, size:2 * size] / 255.0)
        total += amp
        amp *= 0.5
    return acc / total


def deck():
    s, plates = 512, 4
    p = s // plates
    n = tile_noise(s, 8)
    brushed = np.repeat(rng.random((s, 1)), s, axis=1) * 0.08
    base = 0.32 + 0.18 * n + brushed
    height = np.ones((s, s))
    y, x = np.mgrid[0:s, 0:s]
    gx, gy = x % p, y % p
    groove = (gx < 3) | (gy < 3)
    base[groove] = 0.08
    height[groove] = 0.0
    # rivets near plate corners
    for cx in (10, p - 10):
        for cy in (10, p - 10):
            d = np.hypot(gx - cx, gy - cy)
            r = d < 4
            base[r] = 0.75
            height[r] = 1.0 + (4 - d[r]) / 4
    # diamond tread on every other plate
    tread = (((x // p) + (y // p)) % 2 == 0) & (((gx + gy) % 16 < 2) | ((gx - gy) % 16 < 2)) & ~groove
    base[tread] += 0.1
    height[tread] = 1.15
    rgb = np.stack([base * 0.85, base * 0.92, base * 1.05], -1)
    Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8)).save(os.path.join(OUT, "deck.jpg"), quality=88)
    # normal map from height (tileable, wrapped gradient)
    h = np.array(Image.fromarray((height / height.max() * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))) / 255.0
    dx = (np.roll(h, -1, 1) - np.roll(h, 1, 1)) * 3.0
    dy = (np.roll(h, -1, 0) - np.roll(h, 1, 0)) * 3.0
    nz = np.ones_like(h)
    norm = np.sqrt(dx * dx + dy * dy + nz * nz)
    nm = np.stack([-dx / norm, dy / norm, nz / norm], -1) * 0.5 + 0.5
    Image.fromarray((nm * 255).astype(np.uint8)).save(os.path.join(OUT, "deck_normal.png"))


def panel():
    s = 512
    n = tile_noise(s, 6)
    y, x = np.mgrid[0:s, 0:s]
    base = 0.55 + 0.15 * n
    seam = (x % 256 < 4) | (y % 512 < 4) | (y % 512 > 508)
    base[seam] = 0.12
    rgb = np.stack([base * 0.78, base * 0.84, base * 0.95], -1)
    # cyan light strip
    strip = (y > 300) & (y < 316)
    rgb[strip] = [0.25, 0.9, 1.0]
    # vents
    vent = (y > 100) & (y < 180) & ((x % 256) > 60) & ((x % 256) < 196) & ((y % 12) < 5)
    rgb[vent] = rgb[vent] * 0.3
    # hazard stripes at the bottom
    haz = y > 450
    stripe = ((x + y) // 24) % 2 == 0
    rgb[haz & stripe] = [0.95, 0.75, 0.1]
    rgb[haz & ~stripe] = [0.08, 0.08, 0.08]
    Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8)).save(os.path.join(OUT, "panel.jpg"), quality=88)


def stars():
    w, h = 1024, 512
    img = np.zeros((h, w, 3))
    neb = tile_noise(512, 4, 5)
    neb = np.array(Image.fromarray((neb * 255).astype(np.uint8)).resize((w, h), Image.BICUBIC)) / 255.0
    neb = np.clip(neb - 0.45, 0, 1) * 0.6
    img[..., 0] += neb * 0.35
    img[..., 1] += neb * 0.12
    img[..., 2] += neb * 0.55
    for _ in range(2600):
        sx, sy = rng.integers(0, w), rng.integers(0, h)
        b = rng.random() ** 3
        c = np.array([0.8 + 0.2 * rng.random(), 0.85, 1.0]) * (0.3 + 0.7 * b)
        img[sy, sx] = np.maximum(img[sy, sx], c)
        if b > 0.6:
            for ddx, ddy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                img[(sy + ddy) % h, (sx + ddx) % w] = np.maximum(img[(sy + ddy) % h, (sx + ddx) % w], c * 0.45)
    Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8)).save(os.path.join(OUT, "stars.jpg"), quality=90)


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    deck()
    panel()
    stars()
    print("textures written to", os.path.abspath(OUT))
